"""Generate concise result tables, report macros and a failure-case figure."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import numpy as np
import pandas as pd
from ais_origin_table import FOCUSED_METHODS, origin_tables

SCENARIOS = [
    ("suite_stationary", "Stationary"),
    ("suite_drift", "Drifting lane"),
    ("suite_lane_shift", "Lane shift"),
    ("suite_emergence", "Emerging lane"),
]


def tv_disclosure(results: Path) -> tuple[str, str]:
    """Report the saved TV penalty and coverage, without changing any plan."""
    runs = pd.read_csv(results / "robustness" / "runs.csv")
    runs["penalty_pp"] = 100 * (runs.nominal_detection_rate - runs.worst_case_detection_rate)
    macros = []
    penalties = []
    for radius, tag in ((0.05, "Five"), (0.15, "Fifteen")):
        sub = runs[np.isclose(runs.radius, radius)]
        low, high = sub.penalty_pp.min(), sub.penalty_pp.max()
        penalties.append(f"{low:.2f} to {high:.2f} pp at radius {radius:g}")
        macros += [
            f"\\newcommand{{\\tvPenalty{tag}Min}}{{{low:.2f}}}",
            f"\\newcommand{{\\tvPenalty{tag}Max}}{{{high:.2f}}}",
        ]
    covered = runs.groupby(["radius", "scenario", "strategy"]).certificate_applies_on_grid.mean()
    small = covered.loc[0.05]
    stacked = covered.loc[(0.15, slice(None), "stacked")]
    statements = [
        "Nominal minus worst-case detection spans " + "; ".join(penalties) + ".",
        f"At radius 0.05, the maximum truth-coverage fraction across scenarios and strategies is {100 * small.max():.0f}%.",
        "At radius 0.15, stacked-forecast truth coverage is "
        + "; ".join(f"{name.replace('_', ' ')} {100 * value:.0f}%" for name, value in stacked.items())
        + ".",
        "Coverage describes the normalised grid truth in the declared forecast ball. It is not a calibrated operational guarantee.",
    ]
    macros.append(f"\\newcommand{{\\tvSmallCoverageMax}}{{{100 * small.max():.0f}}}")
    for scenario, value in stacked.items():
        tag = "".join(word.capitalize() for word in scenario.split("_"))
        macros.append(f"\\newcommand{{\\tvCoverage{tag}}}{{{100 * value:.0f}}}")
    return "\n\n".join(statements) + "\n", "\n".join(macros) + "\n"


def build_tables(results: Path) -> tuple[str, str, str, str]:
    headline = [
        "| Scenario | Historical misses | Intensity-stacking misses | Relative miss reduction [95% CI] |",
        "|---|---:|---:|---:|",
    ]
    for folder, name in SCENARIOS:
        raw = pd.read_csv(results / folder / "runs.csv")
        a = raw[raw.strategy == "stacked"].set_index("seed").missed
        b = raw[raw.strategy == "pooled"].set_index("seed").missed
        common = a.index.intersection(b.index)
        xa, xb = a.loc[common].to_numpy(), b.loc[common].to_numpy()
        rng = np.random.default_rng(7)
        indices = rng.integers(0, len(common), (4000, len(common)))
        reductions = 100 * (1 - xa[indices].mean(axis=1) / xb[indices].mean(axis=1))
        lo, hi = np.quantile(reductions, [0.025, 0.975])
        reduction = 100 * (1 - xa.mean() / xb.mean())
        summary = pd.read_csv(results / folder / "summary.csv").set_index("strategy")
        hist_miss = 100 * (1 - summary.loc["pooled", "detection_rate_mean"])
        forecast_miss = 100 * (1 - summary.loc["stacked", "detection_rate_mean"])
        headline.append(
            f"| {name} | {hist_miss:.2f}% | {forecast_miss:.2f}% | {reduction:.1f}% [{lo:.1f}, {hi:.1f}] |"
        )
    robust = pd.read_csv(results / "robustness" / "summary.csv")
    table = [
        "| Scenario | Future detection change, pp [95% CI] | Worst-case change, pp | Truth inside TV ball |",
        "|---|---:|---:|---:|",
    ]
    tex = []
    sub = robust[(robust.strategy == "stacked_tv") & np.isclose(robust.radius, 0.15)]
    for _, row in sub.iterrows():
        name = row.scenario.replace("_", " ").capitalize()
        table.append(
            f"| {name} | {row.gain_vs_stacked_pp:+.3f} [{row.gain_lo:+.3f}, {row.gain_hi:+.3f}] | "
            f"{row.worst_case_gain_vs_stacked_pp:+.3f} | {100 * row.fraction_truth_inside_ball:.0f}% |"
        )
        tex.append(
            f"{name} & {row.gain_vs_stacked_pp:+.3f} & {row.worst_case_gain_vs_stacked_pp:+.3f} & "
            f"{100 * row.fraction_truth_inside_ball:.0f}\\% " + chr(92) * 2
        )
    reversal = robust[(robust.scenario == "reversal") & np.isclose(robust.radius, 0)].set_index("strategy")
    macros = ["% generated by scripts/research_summary.py; do not edit"]
    for method, macro in (("pooled", "reversalHistory"), ("stacked", "reversalStacked")):
        macros.append(f"\\newcommand{{\\{macro}}}{{{100 * reversal.loc[method, 'detection_rate_mean']:.2f}}}")
    max_error = robust.max_abs_discretisation_error_pp.max()
    macros.append(f"\\newcommand{{\\robustGridErrorMax}}{{{max_error:.2f}}}")
    return (
        "\n".join(headline) + "\n",
        "\n".join(table) + "\n",
        "\n".join(tex) + "\n\\bottomrule\n",
        "\n".join(macros) + "\n",
    )


def failure_figure(results: Path, out: Path) -> None:
    import matplotlib.pyplot as plt

    from stochplace.figures import _save, _style

    _style()
    summary = pd.read_csv(results / "robustness" / "summary.csv")
    order = ["stationary", "drift", "lane_shift", "emergence", "reversal", "seam_drift"]
    labels = [s.replace("_", " ") for s in order]
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.8))
    y = np.arange(len(order))
    colours = {"pooled": "#eb6834", "stacked": "#2a78d6", "pseudo_bma": "#9969a7"}
    for offset, method, title in (
        (-0.23, "pooled", "history"),
        (0, "stacked", "intensity stacking"),
        (0.23, "pseudo_bma", "pseudo-BMA"),
    ):
        sub = summary[(summary.strategy == method) & (summary.radius == 0)].set_index("scenario").loc[order]
        axes[0].barh(
            y + offset, 100 * sub.detection_rate_mean, height=0.21, color=colours[method], label=title
        )
    axes[0].set_yticks(y, labels)
    axes[0].invert_yaxis()
    axes[0].set_xlim(80, 100)
    axes[0].set_xlabel("expected detection on the true future (%)")
    axes[0].set_title("Extrapolation fails when drift reverses", loc="left")
    axes[0].legend(loc="lower left", ncol=1)
    selected = (
        summary[(summary.strategy == "stacked_tv") & np.isclose(summary.radius, 0.15)]
        .set_index("scenario")
        .loc[order]
    )
    axes[1].axvline(0, color="#8a8984", lw=1)
    mean = selected.gain_vs_stacked_pp.to_numpy()
    lo, hi = selected.gain_lo.to_numpy(), selected.gain_hi.to_numpy()
    axes[1].errorbar(mean, y, xerr=np.vstack([mean - lo, hi - mean]), fmt="o", color="#773aa6", capsize=3)
    axes[1].set_yticks(y, labels)
    axes[1].invert_yaxis()
    axes[1].set_xlabel("TV robust minus intensity stacking (percentage points)")
    axes[1].set_title("Unstructured TV gives little design benefit", loc="left")
    fig.suptitle("Stress tests reveal the assumptions", x=0.07, y=1.02, ha="left", fontsize=16)
    fig.text(
        0.07,
        -0.05,
        f"{int(summary['n'].max())} paired seeds; same finite candidate set. Right: TV radius 0.15, percentile bootstrap over seeds. "
        "Certificates apply only inside the declared grid ambiguity set.",
        fontsize=8.5,
        color="#52514e",
    )
    fig.tight_layout(w_pad=3)
    _save(fig, out, "forecast_failure")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--tables", type=Path, default=Path("docs/tables"))
    parser.add_argument("--paper", type=Path, default=Path("paper"))
    parser.add_argument("--figures", type=Path, default=Path("docs/figures"))
    parser.add_argument("--readme", type=Path, help="refresh the marked result blocks in this README")
    args = parser.parse_args()
    headline, robustness, tex, macros = build_tables(args.results)
    tv_text, tv_macros = tv_disclosure(args.results)
    macros += tv_macros
    args.tables.mkdir(parents=True, exist_ok=True)
    (args.paper / "tables").mkdir(parents=True, exist_ok=True)
    (args.tables / "headline.md").write_text(headline)
    (args.tables / "robustness.md").write_text(robustness)
    (args.tables / "tv_scope.md").write_text(
        "# TV ambiguity as a negative result\n\n"
        + tv_text
        + "\nGenerated by `scripts/research_summary.py` from `results/robustness/runs.csv`. "
        "All four saved strategies are included in the penalty ranges.\n"
    )
    (args.paper / "tables" / "robustness.tex").write_text(tex)
    (args.paper / "robust_numbers.tex").write_text(macros)
    if args.readme is not None:
        content = args.readme.read_text()
        content = re.sub(
            r"(?s)(<!-- headline:start -->).*?(<!-- headline:end -->)",
            lambda match: match[1] + "\n" + headline + match[2],
            content,
        )
        content, count = re.subn(
            r"(?s)(<!-- tv-scope:start -->).*?(<!-- tv-scope:end -->)",
            lambda match: match[1] + "\n" + tv_text + match[2],
            content,
        )
        if count != 1:
            raise ValueError("expected one TV-scope README block")
        ais_file = args.results / "ais_gothenburg" / "summary.csv"
        if ais_file.exists():
            runs = pd.read_csv(args.results / "ais_gothenburg" / "runs.csv")
            ais_table, _ = origin_tables(runs, FOCUSED_METHODS)
            content = re.sub(
                r"(?s)(<!-- ais:start -->).*?(<!-- ais:end -->)",
                lambda match: match[1] + "\n" + ais_table + match[2],
                content,
            )
        args.readme.write_text(content)
    failure_figure(args.results, args.figures)
    print("Updated headline and robustness tables, report macros and stress-test figure.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
