"""Build the README / report tables and key numbers from results/.

Every number quoted in README.md and paper/main.tex comes from the files
this script writes:

* results/key_numbers.json
* docs/tables/*.md         (markdown, for the README)
* paper/tables/*.tex       (LaTeX, for the report)

Usage: python scripts/make_tables.py
"""

