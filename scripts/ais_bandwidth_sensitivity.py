"""Post hoc AIS bandwidth sensitivity; no scale is selected or adopted."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import tempfile
from dataclasses import asdict
from pathlib import Path
from unittest.mock import patch

import numpy as np
import pandas as pd

from stochplace import ais
from stochplace.experiment import _dependency_versions, _git_commit, _source_hash

SCALES = (0.25, 0.5, 1.0, 2.0, 3.0)
STRATEGIES = ("pooled", "recent", "stacked", "lgcp", "hindsight", "fence")
DISCLOSURE = "Post hoc sensitivity computed after viewing the test epochs; not used to select a bandwidth."


def summarise_sensitivity(runs: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (scale, strategy), group in runs.groupby(["scale", "strategy"], sort=True):
        rows.append(
            {
                "scale": scale,
                "strategy": strategy,
                "mean_over_origins": group.detection_rate.mean(),
                "pooled_detection_rate": np.average(group.detection_rate, weights=group.n_test),
                "n_origins": len(group),
            }
        )
    return pd.DataFrame(rows)


def render(results: Path, tables: Path, paper: Path, readme: Path | None = None) -> None:
    summary = pd.read_csv(results / "ais_bandwidth_sensitivity" / "summary.csv")
    wide = summary.pivot(index="scale", columns="strategy", values="mean_over_origins") * 100
    lines = [
        "# AIS bandwidth sensitivity",
        "",
        DISCLOSURE,
        "No scale is adopted. All other settings are unchanged.",
        "",
        "| Bandwidth multiplier | Historical KDE | Recent | Stacked | Historical LGCP | Hindsight | Fence |",
        "|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for scale, row in wide.iterrows():
        lines.append(f"| {scale:g} | " + " | ".join(f"{row[s]:.1f}%" for s in STRATEGIES) + " |")
    default = wide.loc[1.0]
    gaps = default.lgcp - default[["pooled", "recent", "stacked"]]
    fine = wide.loc[0.25]
    statement = (
        f"At the default bandwidth, historical LGCP leads the KDE planners by "
        f"{gaps.min():.1f} to {gaps.max():.1f} percentage points. "
        f"At multiplier 0.25, historical KDE detects {fine.pooled:.1f}%, "
        f"stacking {fine.stacked:.1f}%, and LGCP {fine.lgcp:.1f}%; "
        f"recent epochs remain {fine.lgcp - fine.recent:.1f} points behind LGCP. "
        "This is estimator-resolution sensitivity, not evidence selecting a new setting "
        "or settling history versus forecast.\n"
    )
    lines += [
        "",
        statement,
        "Values are means over the same test origins, not significance tests.",
        "Generated by `scripts/ais_bandwidth_sensitivity.py` from its committed raw runs and summary.",
    ]
    tables.mkdir(parents=True, exist_ok=True)
    paper.mkdir(parents=True, exist_ok=True)
    (tables / "ais_bandwidth_sensitivity.md").write_text("\n".join(lines) + "\n")
    macros = ["% generated by scripts/ais_bandwidth_sensitivity.py; do not edit"]
    for name, value in (
        ("aisBandwidthGapMin", gaps.min()),
        ("aisBandwidthGapMax", gaps.max()),
        ("aisFinePooled", fine.pooled),
        ("aisFineStacked", fine.stacked),
        ("aisFineLgcp", fine.lgcp),
        ("aisFineRecentGap", fine.lgcp - fine.recent),
    ):
        macros.append(f"\\newcommand{{\\{name}}}{{{value:.1f}}}")
    (paper / "ais_sensitivity_numbers.tex").write_text("\n".join(macros) + "\n")
    if readme:
        content, count = re.subn(
            r"(?s)(<!-- ais-sensitivity:start -->).*?(<!-- ais-sensitivity:end -->)",
            lambda m: m[1] + "\n" + statement + m[2],
            readme.read_text(),
        )
        if count != 1:
            raise ValueError("expected one AIS-sensitivity README block")
        readme.write_text(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/raw/ais.gpkg"))
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--tables", type=Path, default=Path("docs/tables"))
    parser.add_argument("--paper", type=Path, default=Path("paper"))
    parser.add_argument("--readme", type=Path)
    parser.add_argument("--render-only", action="store_true")
    args = parser.parse_args()
    if not args.render_only:
        baseline_meta = json.loads((args.results / "ais_gothenburg" / "meta.json").read_text())
        digest = hashlib.sha256(args.data.read_bytes()).hexdigest()
        if digest != baseline_meta["data_sha256"]:
            raise ValueError("AIS data checksum differs from the published study")
        config = ais.AISStudyConfig(strategies=STRATEGIES)
        out = args.results / "ais_bandwidth_sensitivity"
        out.mkdir(parents=True, exist_ok=True)
        bandwidth = ais._bandwidth
        rows = []
        for scale in SCALES:

            def scaled_bandwidth(history, cfg, k=scale):
                return tuple(k * value for value in bandwidth(history, cfg))

            with tempfile.TemporaryDirectory(prefix="ais-scale-") as directory:
                with patch.object(ais, "_bandwidth", scaled_bandwidth):
                    runs = ais.run_case_study(args.data, Path(directory), config)
            rows.append(runs.assign(scale=scale))
            print(f"Completed AIS sensitivity k={scale:g}: {len(runs)} runs", flush=True)
        runs = pd.concat(rows, ignore_index=True)
        summary = summarise_sensitivity(runs)
        baseline = pd.read_csv(args.results / "ais_gothenburg" / "summary.csv").set_index("strategy")
        default = summary[summary.scale == 1].set_index("strategy").loc[list(STRATEGIES)]
        for column in ("mean_over_origins", "pooled_detection_rate", "n_origins"):
            np.testing.assert_allclose(
                default[column],
                baseline.loc[list(STRATEGIES), column],
                rtol=0,
                atol=1e-9,
                err_msg=f"k=1 differs: {column}",
            )
        runs.to_csv(out / "runs.csv", index=False)
        summary.to_csv(out / "summary.csv", index=False)
        meta = {
            "data_sha256": digest,
            "source_sha256": _source_hash(),
            "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "scales": SCALES,
            "strategies": STRATEGIES,
            "config": asdict(config),
            "disclosure": DISCLOSURE,
            "git_commit": _git_commit(),
            "dependencies": _dependency_versions(),
            "bandwidth_scope": "multiply both bandwidths returned by stochplace.ais._bandwidth; other fitting unchanged",
        }
        (out / "meta.json").write_text(json.dumps(meta, indent=2, default=str) + "\n")
    render(args.results, args.tables, args.paper, args.readme)


if __name__ == "__main__":
    main()
