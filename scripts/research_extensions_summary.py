"""Generate research evidence from committed raw runs without selecting favourable cases."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from stochplace.evaluate import bootstrap_ci


def latex_table(title, headers, rows):
    def escape(value):
        return str(value).replace("_", r"\_").replace("%", r"\%")

    return "\n".join(
        [
            r"\Needspace{12\baselineskip}",
            r"\paragraph{" + title + "}",
            r"\begin{center}\small\begin{tabular}{" + "l" * len(headers) + "}",
            r"\toprule",
            " & ".join(escape(h) for h in headers) + r"\\\midrule",
            *(" & ".join(escape(v) for v in row) + r"\\" for row in rows),
            r"\bottomrule\end{tabular}\end{center}",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--tables", type=Path, default=Path("docs/tables"))
    args = parser.parse_args()
    args.tables.mkdir(parents=True, exist_ok=True)
    paper_rows = []
    component_rows, all_strategies = (
        [],
        [
            "| Regime | Method | Detection | Method minus pooled, pp [95% paired CI] | Stacked minus method, pp [95% paired CI] |",
            "|---|---|---:|---:|---:|",
        ],
    )
    holdout = [
        "| Scenario | Stacked minus history detection, pp [95% paired CI] | Positive-gain seeds |",
        "|---|---:|---:|",
    ]
    for path in sorted(args.results.glob("holdout_*/runs.csv")):
        runs = pd.read_csv(path)
        wide = runs.pivot(index="seed", columns="strategy", values="detection_rate")
        scenario = path.parent.name.removeprefix("holdout_")
        for method in sorted(wide.columns):
            m, lo, hi = bootstrap_ci((100 * (wide[method] - wide.pooled)).to_numpy())
            s, slo, shi = bootstrap_ci((100 * (wide.stacked - wide[method])).to_numpy())
            all_strategies.append(
                f"| {scenario} | {method} | {100 * wide[method].mean():.2f}% | {m:+.2f} [{lo:+.2f}, {hi:+.2f}] | {s:+.2f} [{slo:+.2f}, {shi:+.2f}] |"
            )
            if method in ("recent", "drift_u", "trend"):
                component_rows.append([scenario, method, f"{s:+.2f} [{slo:+.2f}, {shi:+.2f}]"])
        gain = 100 * (wide.stacked - wide.pooled)
        mean, low, high = bootstrap_ci(gain.to_numpy())
        paper_rows.append(
            [
                path.parent.name.removeprefix("holdout_"),
                f"{mean:+.2f} [{low:+.2f}, {high:+.2f}]",
                f"{(gain > 0).sum()}/{len(gain)}",
            ]
        )
        holdout.append(
            f"| {path.parent.name.removeprefix('holdout_')} | {mean:+.2f} [{low:+.2f}, {high:+.2f}] | {(gain > 0).sum()}/{len(gain)} |"
        )
    holdout += [
        "",
        "All preregistered regimes and seeds are shown. These gains test the specified generators, not operational traffic.",
        "Generated by `scripts/research_extensions_summary.py` from `results/holdout_*/runs.csv`.",
    ]
    (args.tables / "holdout_scenarios.md").write_text("\n".join(holdout) + "\n")
    all_strategies += [
        "",
        "Secondary descriptive comparisons added after the external audit; the frozen primary contrast remains stacked minus pooled. Every strategy is shown, including losses. Intervals use the existing paired-seed bootstrap without multiplicity adjustment; no best component is selected as a new test target.",
    ]
    (args.tables / "holdout_components.md").write_text("\n".join(all_strategies) + "\n")
    records = []
    for path in sorted(args.results.glob("*/runs.csv")):
        runs = pd.read_csv(path)
        if "sample_rank" not in runs or "strategy" not in runs:
            continue
        keys = [c for c in runs if c.startswith("param_")] + ["horizon", "strategy"]
        eligible = runs[runs.sample_rank.notna() & ~runs.strategy.str.contains(":")]
        for key, group in eligible.groupby(keys, sort=True):
            values = key if isinstance(key, tuple) else (key,)
            record = {"study": path.parent.name, **dict(zip(keys, values))}
            record.update(
                mean_rank=group.sample_rank.mean(),
                coverage_90=group.sample_covered_90.astype(float).mean(),
                mean_sample_mismatch=group.sample_mean_relative_l1.mean(),
                n=len(group),
            )
            records.append(record)
    calibration = pd.DataFrame(records)
    if len(calibration):
        calibration.to_csv(args.results / "calibration_diagnostics.csv", index=False)
        selected = calibration[calibration.study.str.startswith(("suite_", "holdout_"))]
        rows = [
            "| Study | Forecast | Mean latent-loss rank | Central 90% coverage | Mean sample-mean mismatch | Seeds |",
            "|---|---|---:|---:|---:|---:|",
        ]
        for _, row in selected.iterrows():
            rows.append(
                f"| {row.study} | {row.strategy} | {row.mean_rank:.3f} | {100 * row.coverage_90:.1f}% | {row.mean_sample_mismatch:.3f} | {int(row.n)} |"
            )
        rows += [
            "",
            "These are empirical ranks and coverage of latent expected missed mass on the planning grid, not the PIT of realised Poisson counts.",
            "Only expected-objective plans are shown. The complete sweep diagnostics are in `results/calibration_diagnostics.csv`.",
            "No nominal coverage claim or sampler adoption follows from this table alone.",
            "The component sampler and component forecasters reuse fixed Monte Carlo streams across history seeds. These are conditional diagnostics with common random numbers, not 40 independent sampler-noise realizations. History and scenario seeds still vary.",
        ]
        (args.tables / "calibration_diagnostics.md").write_text("\n".join(rows) + "\n")

    sampler = pd.read_csv(args.results / "sampler_calibration/summary.csv")
    gate = json.loads((args.results / "sampler_calibration/gate.json").read_text())
    sampler_rows = []
    sampler_md = [
        "| Regime | Sampler | Mean rank | 90% interval coverage | Mean sample mismatch |",
        "|---|---|---:|---:|---:|",
    ]
    for _, row in sampler.iterrows():
        values = [
            row.scenario,
            row.method,
            f"{row.sample_rank:.3f}",
            f"{100 * row.sample_covered_90:.1f}%",
            f"{row.sample_mean_relative_l1:.3f}",
        ]
        sampler_rows.append(values)
        sampler_md.append("| " + " | ".join(values) + " |")
    sampler_md += [
        "",
        "Frozen gate: every regime must have coverage >=80%, mean rank in [0.35,0.65], and mean mismatch <=0.10.",
        "",
        *[
            f"- {method}: {'eligible' if passed else 'ineligible'} for further study."
            for method, passed in gate["eligible_for_further_study"].items()
        ],
        "",
        "No candidate is adopted. These diagnostics do not validate the full predictive law.",
    ]
    (args.tables / "sampler_candidates.md").write_text("\n".join(sampler_md) + "\n")

    bandwidth = pd.read_csv(args.results / "ais_training_bandwidth/runs.csv")
    ais_rows, ais_md = (
        [],
        [
            "| Origin | Method | Training-selected scale | Detection | Change from default historical KDE, pp |",
            "|---:|---|---:|---:|---:|",
        ],
    )
    for _, row in bandwidth.iterrows():
        values = [
            str(row.origin),
            row.method,
            f"{row.scale:g}",
            f"{100 * row.detection_rate:.2f}%",
            f"{row.paired_gain_pp:+.2f}",
        ]
        ais_rows.append(values)
        ais_md.append("| " + " | ".join(values) + " |")
    ais_md += [
        "",
        "Every origin is shown. Scale selection uses training targets only. This reuses the already viewed one-day sample and is exploratory; overlapping origins are not independent population replicates.",
    ]
    frozen_scales = json.loads((args.results / "ais_training_bandwidth/meta.json").read_text())["config"][
        "scales"
    ]
    lower_scale = min(frozen_scales)
    boundary = int(bandwidth.scale.eq(lower_scale).sum())
    ais_wide = bandwidth.pivot(index="origin", columns="method", values="detection_rate")
    origin_differences = 100 * (ais_wide.stacked - ais_wide.pooled)
    ais_scope = f"{boundary}/{len(bandwidth)} choices select {lower_scale:g}, the lower edge of the frozen grid; the grid does not bracket an interior optimum. It is not extended on this reused day. Stacking exceeds pooled history at {int((origin_differences > 0).sum())}/{len(origin_differences)} origins; its largest deficit, at origin {origin_differences.idxmin()}, drives the mean comparison."
    ais_md += [
        "",
        ais_scope,
        "",
        "| Origin | Training-selected stacking minus training-selected pooled, pp |",
        "|---:|---:|",
        *[f"| {origin} | {gain:+.2f} |" for origin, gain in origin_differences.items()],
    ]
    (args.tables / "ais_training_bandwidth.md").write_text("\n".join(ais_md) + "\n")

    policies = pd.read_csv(args.results / "ais_policy_ablation/runs.csv")
    policies_md = [
        "| Origin | Method | Policy | Detection | Paired change, pp | Backtests | Weights |",
        "|---:|---|---|---:|---:|---:|---|",
    ]
    for _, row in policies.iterrows():
        weights = ", ".join(f"{k}={v:.4f}" for k, v in json.loads(row.weights).items())
        policies_md.append(
            f"| {row.origin} | {row.method} | {row.policy} | {100 * row.detection_rate:.2f}% | {row.paired_gain_pp:+.2f} | {row.backtest_origins} | {weights} |"
        )
    policies_md += [
        "",
        "Paired changes use the same default historical KDE reference. Minimum-origin fallback uses pooled history before three usable backtests. Relative floors are an experimental score ablation; defaults are unchanged. Full-precision weights and solver status are retained in the raw CSV.",
    ]
    (args.tables / "ais_policy_ablation.md").write_text("\n".join(policies_md) + "\n")
    policy_rows = [
        [row.method, row.policy, f"{100 * row.detection_rate:.2f}%", f"{row.paired_gain_pp:+.2f}"]
        for _, row in pd.read_csv(args.results / "ais_policy_ablation/summary.csv").iterrows()
    ]

    transport = pd.read_csv(args.results / "transport_geometry/runs.csv")
    plan_counts, calibration_rows = [], []

    def plan_key(value):
        return tuple(sorted(tuple(point) for point in json.loads(value)))

    for (scenario, method), group in transport[transport.method.isin(["tv", "w1"])].groupby(
        ["scenario", "method"], sort=True
    ):
        baseline = transport[(transport.scenario == scenario) & (transport.method == "nominal_" + method)]
        plan_counts.append(
            [
                scenario,
                method,
                str(baseline.sensors_full.map(plan_key).nunique()),
                str(group.sensors_full.map(plan_key).nunique()),
            ]
        )
        first_sets_radius = sum(
            abs(json.loads(row.calibration_errors)[0] - row.radius) <= 1e-12 for _, row in group.iterrows()
        )
        ratios = group.radius / group.truth_distance.replace(0, np.nan)
        calibration_rows.append(
            [scenario, method, f"{first_sets_radius}/{len(group)}", f"{ratios.median():.2f}"]
        )
    transport_rows, transport_md = (
        [],
        [
            "| Regime | Ball | Future gain over nominal, pp [95% paired CI] | Truth inside ball | Changed plans | Mean worst-case gain, pp |",
            "|---|---|---:|---:|---:|---:|",
        ],
    )
    for (scenario, method), group in transport[transport.method.isin(["tv", "w1"])].groupby(
        ["scenario", "method"], sort=True
    ):
        mean, low, high = bootstrap_ci(group.gain_vs_nominal_pp.to_numpy())
        degenerate = abs(high - low) <= 1e-12
        values = [
            scenario,
            method,
            f"{mean:+.3f} [{low:+.3f}, {high:+.3f}]" + (" (D)" if degenerate else ""),
            f"{100 * group.certificate_applies.mean():.0f}%",
            f"{group.plan_changed.sum()}/{len(group)}",
            f"{group.worst_case_gain_pp.mean():+.3f}",
        ]
        transport_rows.append(values)
        transport_md.append("| " + " | ".join(values) + " |")
    transport_md += [
        "",
        "All six regimes and 20 seeds are included. The certificate applies only to normalized truth on the planning grid when it lies in the ball. Three training calibration errors do not establish nominal coverage. TV and W1 radii have different units. The discrete outer search is a heuristic; this is an exploratory small-grid study.",
    ]
    transport_scope = "The first calibration target (5) uses four history epochs: stacking has no usable weight-validation backtest and returns pooled history. Thus radii can be driven by an immature pooled forecast rather than the eight-epoch stacked plan. This also affects the first residual-bootstrap factor in C3. These negative results are conditional on the fixed calibration rule; they do not isolate geometry as the cause. The rule and all original outcomes are retained."
    plan_md = [
        "| Regime | Ball | Distinct nominal plans | Distinct robust plans |",
        "|---|---|---:|---:|",
        *["| " + " | ".join(row) + " |" for row in plan_counts],
    ]
    calibration_md = [
        "| Regime | Ball | First error attains radius | Median radius / realized truth distance |",
        "|---|---|---:|---:|",
        *["| " + " | ".join(row) + " |" for row in calibration_rows],
    ]
    transport_md += [
        "",
        transport_scope,
        "",
        *plan_md,
        "",
        "Intervals marked (D) have zero width and are degenerate; they reflect repeated discrete plans, not high population precision.",
        "",
        *calibration_md,
        "",
        "The ratio is a retrospective diagnostic; truth distances are never used to choose radii.",
    ]
    (args.tables / "transport_geometry.md").write_text("\n".join(transport_md) + "\n")

    tuned = bandwidth.groupby("method").detection_rate.mean()
    transport_means = transport[transport.method == "w1"].groupby("scenario").gain_vs_nominal_pp.mean()
    conclusion = (
        "C1 gains against pooled history do not establish superiority to individual components; the full paired comparisons include component wins. "
        f"On the reused AIS day, training-selected historical KDE averages {100 * tuned['pooled']:.2f}% "
        f"detection versus {100 * tuned['stacked']:.2f}% for training-selected stacking. "
        f"Stacking exceeds history at {int((origin_differences > 0).sum())}/{len(origin_differences)} origins; the mean gap is driven by origin {origin_differences.idxmin()}. The geometry-aware transport plan reduces "
        f"mean future detection in {int((transport_means < 0).sum())}/{len(transport_means)} tested regimes "
        f"under the fixed calibration rule, which can be driven by pooled-history backtests. This does not isolate the effect of geometry. Both sampler candidates fail their frozen "
        f"eligibility gate. No experimental method or bandwidth setting is adopted."
    )
    readme = Path("README.md")
    start, end = "<!-- extension-summary:start -->", "<!-- extension-summary:end -->"
    content = readme.read_text()
    if start in content:
        before, rest = content.split(start, 1)
        _, after = rest.split(end, 1)
        content = before + start + "\n" + conclusion + "\n" + end + after
    else:
        marker = "Reproduce the extension with"
        content = content.replace(marker, start + "\n" + conclusion + "\n" + end + "\n\n" + marker, 1)
    readme.write_text(content)

    report = [
        "# Locally frozen research extension results",
        "Generated from raw runs by `scripts/research_extensions_summary.py`. Protocol and candidate commits precede outcomes in the preserved local history; there is no external preregistration timestamp. All original summaries match the pre-C checkpoint at absolute tolerance 1e-9.",
        conclusion,
        "## Shifts outside the candidate families (C1)",
        "\n".join(holdout),
        "\n".join(all_strategies),
        "## Latent-loss diagnostics and sampler gate (C2/C3)",
        "See [all expected-plan diagnostics](tables/calibration_diagnostics.md). Empirical ranks and interval coverage concern latent expected missed mass, not realized-count PIT or calibration of a full point process.",
        "\n".join(sampler_md),
        "## Training-only bandwidth selection on the reused AIS day (C4)",
        "\n".join(ais_md),
        "## AIS policy ablations (C6)",
        "\n".join(policies_md),
        "## Geometry-aware transport ambiguity (C5)",
        "\n".join(transport_md),
        "## Multi-week AIS dependency (C7)",
        "Blocked: no raw archive was acquired or checksummed. The fixed design and access evidence are in [data_access.md](data_access.md). There is no multi-week empirical result.",
    ]
    Path("docs/research_results.md").write_text("\n\n".join(report) + "\n")
    tex = [
        r"\section{Locally frozen extension studies}",
        "Protocol and candidate commits precede the outcomes in the preserved local history; no external preregistration timestamp exists. All original study summaries are unchanged relative to the corrected pre-extension checkpoint. New methods remain experimental; no sampler or AIS policy replaces a default.",
        latex_table(
            "Shifts outside the candidate families (40 paired seeds)",
            ["Regime", "Stacked minus history, pp [95% CI]", "Positive seeds"],
            paper_rows,
        ),
        "Intervals resample paired seeds. These are specified synthetic generators, not operational traffic.",
        latex_table(
            "Secondary component comparisons",
            ["Regime", "Component", "Stacked minus component, pp [95% CI]"],
            component_rows,
        ),
        "These descriptive comparisons were added after the audit. The primary contrast remains stacked minus pooled; complete comparisons with every strategy are in the generated holdout component table. Intervals are not adjusted for multiple comparisons.",
        r"\clearpage",
        latex_table(
            "Sampler diagnostics on the same expected-loss plans",
            ["Regime", "Sampler", "Rank", "Coverage", "Mismatch"],
            sampler_rows,
        ),
        "The gate requires every regime to have at least 80\\% coverage, mean rank in $[.35,.65]$ and mean relative sample-mean mismatch at most $.10$. Eligibility for further study: "
        + "; ".join(
            method.replace("_", r"\_") + (" passes" if passed else " fails")
            for method, passed in gate["eligible_for_further_study"].items()
        )
        + ". No sampler is adopted. These are latent-loss ensemble diagnostics, not realized-count PIT or validation of the full point-process law. Fixed Monte Carlo streams are reused across history seeds: these are conditional diagnostics with common random numbers, not independent sampler-noise realizations.",
        r"\clearpage",
        latex_table(
            "Training-only AIS bandwidth selection",
            ["Origin", "Method", "Scale", "Detection", "Paired change, pp"],
            ais_rows,
        ),
        "Changes use the default historical KDE reference. Selection uses targets strictly before each test origin. The previously viewed one-day sample is reused: this is exploratory reanalysis, with no population significance claim.",
        ais_scope,
        latex_table(
            "AIS policy ablations (mean over four origins)",
            ["Method", "Policy", "Detection", "Paired change, pp"],
            policy_rows,
        ),
        "Origin-level weights, solver status and all individual detections are retained in the raw CSV and the generated AIS policy table. Minimum-origin and relative-floor rules are ablations only; the original policy remains the default.",
        r"\clearpage",
        latex_table(
            "Geometry-aware ambiguity (20 paired seeds)",
            ["Regime", "Ball", "Future gain, pp [95% CI]", "Inside", "Changed", "WC gain"],
            transport_rows,
        ),
        "The transport plan lowers mean future detection in "
        + str(int((transport_means < 0).sum()))
        + "/"
        + str(len(transport_means))
        + " tested regimes under this fixed calibration rule. This negative result does not isolate geometry as the cause.",
        "The finite-grid transport dual was checked against an independently formulated primal LP on four-cell unit fixtures. Every certificate is conditional on normalized grid truth lying in its ball. Three chronological training errors do not establish nominal coverage. Search is discrete and heuristic; no global placement or operational guarantee is claimed. The Wasserstein construction is established \\citep{gao2023wasserstein,esfahani2018wasserstein}; distributionally robust coverage control also predates this study \\citep{boskos2023coverage}.",
        transport_scope,
        r"\clearpage",
        latex_table(
            "Distinct discrete plans across 20 history seeds",
            ["Regime", "Ball", "Nominal", "Robust"],
            plan_counts,
        ),
        "Intervals marked (D) have zero width and are degenerate; they reflect repeated discrete plans, not population precision.",
        latex_table(
            "Calibration-rule diagnostic",
            ["Regime", "Ball", "First error sets radius", "Median radius/truth distance"],
            calibration_rows,
        ),
        "These truth-distance ratios are retrospective diagnostics and never select a radius. The first calibration prefix returns pooled history because no weight-validation backtest is usable.",
        r"\paragraph{Multi-week AIS (C7)} The proposed July 2020 routing-change study remains blocked by archive access. No raw archive, checksum or multi-week result is reported. Settings and the data dependency are recorded in the repository.",
    ]
    Path("paper/extension_results.tex").write_text("\n\n".join(tex) + "\n")


if __name__ == "__main__":
    main()
