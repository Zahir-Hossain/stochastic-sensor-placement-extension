"""Describe the saved drift failure without rerunning or changing an experiment."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from stochplace.evaluate import bootstrap_ci


def analyse(results: Path) -> dict[str, float | int]:
    runs = pd.read_csv(results / "suite_drift" / "runs.csv")
    if runs.duplicated(["seed", "strategy"]).any():
        raise ValueError("expected one drift run per seed and strategy")
    wide = runs.pivot(index="seed", columns="strategy", values="detection_rate")
    if wide[["stacked:void", "stacked", "pooled", "oracle"]].isna().any().any():
        raise ValueError("unpaired drift runs")
    gaps = 100 * (wide.oracle - wide["stacked:void"])
    mean, lo, hi = bootstrap_ci(gaps.to_numpy())
    history_difference = 100 * (wide["stacked:void"] - wide.pooled)
    hm, hlo, hhi = bootstrap_ci(history_difference.to_numpy())
    weights = runs[runs.strategy == "stacked:void"].set_index("seed").weights
    non_drift = weights.map(lambda x: sum(json.loads(x)[k] for k in ("pooled", "recent", "trend")))
    return {
        "seeds": len(wide),
        "gap_pp": mean,
        "gap_lo": lo,
        "gap_hi": hi,
        "seeds_gap_over_one_pp": int((gaps > 1).sum()),
        "non_drift_weight_gap_correlation": float(np.corrcoef(gaps, non_drift.loc[gaps.index])[0, 1]),
        "history_difference_pp": hm,
        "history_difference_lo": hlo,
        "history_difference_hi": hhi,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--tables", type=Path, default=Path("docs/tables"))
    parser.add_argument("--paper", type=Path, default=Path("paper"))
    parser.add_argument("--readme", type=Path)
    args = parser.parse_args()
    v = analyse(args.results)
    args.tables.mkdir(parents=True, exist_ok=True)
    args.paper.mkdir(parents=True, exist_ok=True)
    text = (
        f"Gap to the true-intensity heuristic: **{v['gap_pp']:.2f} "
        f"[{v['gap_lo']:.2f}, {v['gap_hi']:.2f}] pp**; "
        f"{v['seeds_gap_over_one_pp']} of {v['seeds']} seeds exceed 1 pp. "
        f"Correlation with non-drift component weight: {v['non_drift_weight_gap_correlation']:.2f}. "
        f"Detection difference from history: **{v['history_difference_pp']:+.2f} "
        f"[{v['history_difference_lo']:+.2f}, {v['history_difference_hi']:+.2f}] pp**. "
        "The paired percentile interval includes zero, so the lower mean does not establish "
        "a reliable loss to history across seeds.\n"
    )
    (args.tables / "void_failure.md").write_text(
        "# Expected-void planning under drift\n\n"
        + text
        + "\nComputed only from `results/suite_drift/runs.csv` by "
        "`scripts/void_failure_analysis.py`; bootstrap over paired seeds. "
        "The heuristic reference is not a global optimum.\n"
    )
    macros = ["% generated by scripts/void_failure_analysis.py; do not edit"]
    for key, name in (
        ("gap_pp", "voidDriftGap"),
        ("gap_lo", "voidDriftGapLo"),
        ("gap_hi", "voidDriftGapHi"),
        ("history_difference_pp", "voidDriftHistory"),
        ("history_difference_lo", "voidDriftHistoryLo"),
        ("history_difference_hi", "voidDriftHistoryHi"),
        ("non_drift_weight_gap_correlation", "voidDriftCorr"),
    ):
        macros.append(f"\\newcommand{{\\{name}}}{{{v[key]:.2f}}}")
    for key, name in (("seeds", "voidDriftSeeds"), ("seeds_gap_over_one_pp", "voidDriftOverOne")):
        macros.append(f"\\newcommand{{\\{name}}}{{{v[key]}}}")
    (args.paper / "void_numbers.tex").write_text("\n".join(macros) + "\n")
    if args.readme:
        content = args.readme.read_text()
        pattern = r"(?s)(<!-- void-failure:start -->).*?(<!-- void-failure:end -->)"
        content, count = re.subn(pattern, lambda m: m[1] + "\n" + text + m[2], content)
        if count != 1:
            raise ValueError("expected one void-failure README block")
        args.readme.write_text(content)
    print(json.dumps(v, indent=2))


if __name__ == "__main__":
    main()
