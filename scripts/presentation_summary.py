"""Generate the visitor overview from saved runs; never rerun or select a method."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from stochplace.evaluate import bootstrap_ci


def paired_record(runs, label, reference, source, note):
    wide = runs.pivot(index="seed", columns="strategy", values="detection_rate")
    mean, low, high = bootstrap_ci((100 * (wide.stacked - wide[reference])).to_numpy())
    return {
        "label": label,
        "reference": reference,
        "n": len(wide),
        "mean_pp": mean,
        "low_pp": low,
        "high_pp": high,
        "source": source,
        "note": note,
    }


def overview(results):
    drift = pd.read_csv(results / "suite_drift/runs.csv")
    robustness = pd.read_csv(results / "robustness/runs.csv")
    reversal = robustness[(robustness.scenario == "reversal") & (robustness.radius == 0)]
    split = pd.read_csv(results / "holdout_lane_split/runs.csv")
    records = [
        paired_record(drift, "Designed drift", "pooled", "suite_drift/runs.csv", "Matches a forecaster"),
        paired_record(
            reversal,
            "Unannounced reversal",
            "pooled",
            "robustness/runs.csv; scenario=reversal, radius=0",
            "History wins",
        ),
        paired_record(
            split,
            "Lane split",
            "trend",
            "holdout_lane_split/runs.csv",
            "Secondary component contrast",
        ),
    ]
    ais = pd.read_csv(results / "ais_training_bandwidth/runs.csv").pivot(
        index="origin", columns="method", values="detection_rate"
    )
    differences = 100 * (ais.stacked - ais.pooled)
    records.append(
        {
            "label": "AIS: training-selected bandwidth",
            "reference": "pooled",
            "n": len(ais),
            "mean_pp": differences.mean(),
            "low_pp": np.nan,
            "high_pp": np.nan,
            "source": "ais_training_bandwidth/runs.csv",
            "note": "Overlapping origins; no population interval",
        }
    )

    reductions = []
    for scenario in ["drift", "lane_shift", "emergence"]:
        raw = pd.read_csv(results / f"suite_{scenario}/runs.csv")
        losses = raw.groupby("strategy").missed.mean()
        reductions.append(100 * (1 - losses.stacked / losses.pooled))
    holdout_gains, component_gaps = [], []
    for path in sorted(results.glob("holdout_*/runs.csv")):
        means = pd.read_csv(path).groupby("strategy").detection_rate.mean()
        holdout_gains.append(means.stacked - means.pooled)
        component_gaps.append(means[["pooled", "recent", "drift_u", "trend"]].max() - means.stacked)
    transport = pd.read_csv(results / "transport_geometry/runs.csv")
    w1 = transport[transport.method == "w1"].groupby("scenario").gain_vs_nominal_pp.mean()
    gate = json.loads((results / "sampler_calibration/gate.json").read_text())
    eligible = gate["eligible_for_further_study"]
    table = "\n".join(
        [
            "| Evidence | Result |",
            "|---|---|",
            f"| Three designed shifts matching a candidate (40 seeds each) | {min(reductions):.1f}-{max(reductions):.1f}% fewer expected misses than historical planning |",
            f"| Five shifts outside the candidate families (40 seeds each) | Higher mean detection than history in {sum(g > 0 for g in holdout_gains)}/5; lower mean than the best single component in {sum(g > 0 for g in component_gaps)}/5, by up to {100 * max(component_gaps):.2f} pp |",
            f"| Unannounced drift reversal (20 seeds) | Stacking minus history: {records[1]['mean_pp']:+.2f} pp detection |",
            f"| One AIS day, four overlapping origins | Training-selected history {100 * ais.pooled.mean():.2f}%; stacking {100 * ais.stacked.mean():.2f}%. Stacking is ahead at {int((differences > 0).sum())}/4 origins |",
            f"| Transport ambiguity (20 seeds per regime) | Lower mean future detection in {int((w1 < 0).sum())}/{len(w1)} regimes under the fixed radius-calibration rule |",
            f"| Frozen sampler gate | {sum(eligible.values())}/{len(eligible)} alternative samplers eligible; current component sampler also fails |",
        ]
    )
    macros = "\n".join(
        [
            "% Generated by scripts/presentation_summary.py; do not edit.",
            f"\\newcommand{{\\overviewAISHistory}}{{{100 * ais.pooled.mean():.2f}}}",
            f"\\newcommand{{\\overviewAISStacked}}{{{100 * ais.stacked.mean():.2f}}}",
            f"\\newcommand{{\\overviewComponentGap}}{{{100 * max(component_gaps):.2f}}}",
            f"\\newcommand{{\\overviewWFailures}}{{{int((w1 < 0).sum())}}}",
            f"\\newcommand{{\\overviewWRegimes}}{{{len(w1)}}}",
        ]
    )
    return pd.DataFrame(records), differences, table, macros + "\n"


def draw(records, differences, out):
    import matplotlib.pyplot as plt

    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10})
    fig, ax = plt.subplots(figsize=(10.2, 4.8))
    fig.subplots_adjust(left=0.32, right=0.97, bottom=0.21, top=0.84)
    ax.axvline(0, color="#7c8798", lw=1)
    labels = []
    for i, row in records.iterrows():
        color = "#157f78" if row.mean_pp > 0 else "#b6573b"
        if np.isfinite(row.low_pp):
            ax.errorbar(
                row.mean_pp,
                i,
                xerr=[[row.mean_pp - row.low_pp], [row.high_pp - row.mean_pp]],
                fmt="o",
                color=color,
                capsize=4,
                markersize=7,
                lw=2,
            )
            value = f"{row.mean_pp:+.2f} [{row.low_pp:+.2f}, {row.high_pp:+.2f}]"
        else:
            ax.scatter(differences, np.full(len(differences), i + 0.08), s=24, color="#85909d")
            ax.scatter([row.mean_pp], [i - 0.08], s=65, marker="D", color=color, zorder=3)
            value = f"{row.mean_pp:+.2f} mean; grey dots = all 4 origins"
        ax.annotate(
            value, (row.mean_pp, i), xytext=(0, -19), textcoords="offset points", ha="center", fontsize=8
        )
        reference = "history" if row.reference == "pooled" else row.reference
        units = "overlapping origins" if i == 3 else "paired seeds"
        labels.append(f"{row.label}\n{row.n} {units}; reference = {reference}")
    ax.set_yticks(range(len(records)), labels)
    ax.set_ylim(3.55, -0.5)
    ax.set_xlim(-19, 10)
    ax.set_xlabel("Stacking minus reference: future detection (percentage points)", labelpad=13)
    ax.spines[["top", "right", "left"]].set_visible(False)
    ax.spines["bottom"].set_color("#c7cdd4")
    ax.tick_params(axis="y", length=0, pad=12)
    ax.grid(axis="x", alpha=0.15)
    ax.set_axisbelow(True)
    fig.suptitle(
        "Forecast-aware placement helps in some tests and loses in others",
        x=0.04,
        ha="left",
        fontsize=14,
        weight="bold",
        color="#203447",
    )
    fig.text(
        0.04,
        0.015,
        "Synthetic bars: existing 95% paired-seed bootstrap intervals. Lane-split contrast is secondary, without multiplicity adjustment.\nAIS diamond: descriptive mean on one reused day; no population interval. Complete comparisons are in docs/research_results.md.",
        fontsize=8,
        color="#4c5968",
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=180, facecolor="white")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated text/data without rendering")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    records, differences, table, macros = overview(root / "results")
    start, end = "<!-- at-a-glance:start -->", "<!-- at-a-glance:end -->"
    readme = root / "README.md"
    content = readme.read_text()
    before, rest = content.split(start, 1)
    _, after = rest.split(end, 1)
    updated = before + start + "\n" + table + "\n" + end + after
    outputs = {
        readme: updated,
        root / "docs/tables/at_a_glance.md": table + "\n",
        root / "docs/figures/research_overview_data.csv": records.to_csv(index=False, float_format="%.12g"),
        root / "paper/presentation_numbers.tex": macros,
    }
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Stale generated overview: {path.relative_to(root)}")
        else:
            path.write_text(text)
    if not args.check:
        draw(records, differences, root / "docs/figures/research_overview.png")
    print("Overview text and source data verified." if args.check else "Overview generated from saved runs.")


if __name__ == "__main__":
    main()
